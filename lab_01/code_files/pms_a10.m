A = 1; 
f1 = 20; 
f2 = 21;
t = 0:0.01:6;
x1 = A * sin(2 * pi * f1 * t);
x2 = A * sin(2 * pi * f2 * t);
x = x1 + x2;
figure;
subplot(2, 1, 1); 
plot(t, x1, 'b-', 'DisplayName', 'x_1'); 
hold on;
plot(t, x2, 'r-', 'DisplayName', 'x_2'); 
hold off;
grid on;
xlim([0, 6]);
ylim([-2, 2]);
legend('show', 'Location', 'northeast');
subplot(2, 1, 2);
plot(t, x, 'k-', 'DisplayName', 'Διακρότημα (x)');
grid on;
xlabel('t');
xlim([0, 6]);
ylim([-2, 2]);
legend('show', 'Location', 'northeast');